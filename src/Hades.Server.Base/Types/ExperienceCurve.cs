namespace Darkages.Types
{
    /// <summary>
    /// 한 레벨을 올리는 데 드는 경험치. 원작이 쓰던 표다.
    /// </summary>
    /// <remarks>
    /// <para>
    /// 원작과 서버팩들은 이것을 표로 싣는다 — `db/server/experience.txt`(직업 레벨 점수 값). 5.99 와
    /// NovaOnline 의 표가 **완전히 같고** 혼든만 다르므로, 둘이 일치하는 그 표를 원작으로 본다. 직업 1~5 는 같은 줄이고
    /// 직업 0(평민)만 98 레벨 값이 다르다 — 여기는 직업 1~5 의 줄이다.
    /// </para>
    /// <para>
    /// <b>표의 값은 누적이 아니라 그 한 레벨의 값이다</b>(2026-09-26, 5.99 <c>Novaonline.exe</c> 역어셈블): 경험치를 더하는
    /// 함수(0x4696e4)가 보유경험치를 표[직업][레벨+1] 과 견주고(0x469989·0x4699cb), 레벨이 오르면 보유경험치를 0 으로
    /// 되돌린다(0x469b15). 5.99 세이브 7개도 모두 보유경험치 &lt; 표[L] 이라 누적으로는 맞지 않는다. 예전에는 이 표를
    /// 누적으로 읽어 차분(600, 1,800, 3,000 …)을 썼고, 50 레벨 근처에서 원작의 약 25분의 1 이었다.
    /// </para>
    /// <para>
    /// 다른 점 하나: 5.99 는 레벨이 오를 때 넘친 몫을 버리지만, 우리 서버는 다음 레벨로 넘긴다(<c>monsterexp.cs</c> <c>HandleExp</c>).
    /// </para>
    /// </remarks>
    public static class ExperienceCurve
    {
        /// <summary>5.99 <c>experience.txt</c> 직업 1~5 의 넷째 칸, 레벨 0~99. 자리 = 그 레벨이 되는 데 드는 값.</summary>
        private static readonly uint[] Table =
        {
